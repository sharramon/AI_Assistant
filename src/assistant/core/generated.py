"""`generated/`: files the core builds from the live modules. Never hand-edited, safe to delete.

Three JSON files, rewritten whole at start and on every module state change:
`modules.json` (the live module list), `directory.json` (each module's line plus its menu, and the
core's own menu) and `dependencies.json` (each module's `needs`, `requires` and `packages`).
A failed write is logged, never raised: the lifecycle must not trip over a file.
"""

from __future__ import annotations

import json
import logging
import os
from collections.abc import Callable
from pathlib import Path
from typing import Any

from assistant.contracts import ToolSpec
from assistant.core.directory import CORE_ID
from assistant.core.lifecycle import LifecycleManager
from assistant.core.permissions.rules import REPO

log = logging.getLogger(__name__)

NOTE = "Generated by the core (src/assistant/core/generated.py) from the live modules. Don't edit; safe to delete."


class GeneratedFiles:
    def __init__(self, folder: Path | None, lifecycle: LifecycleManager, core_specs: Callable[[], list[ToolSpec]]):
        """`folder` None writes nothing (the default without `[core] generated_dir`, so tests stay clean)."""
        self.folder = folder
        self._lifecycle = lifecycle
        self._core_specs = core_specs

    @classmethod
    def from_config(cls, generated_dir: str | None, lifecycle: LifecycleManager,
                    core_specs: Callable[[], list[ToolSpec]]) -> GeneratedFiles:
        """`[core] generated_dir`: relative to the repo unless absolute; empty or missing for none."""
        folder = None
        if generated_dir:
            folder = Path(generated_dir)
            if not folder.is_absolute():
                folder = REPO / folder
        return cls(folder, lifecycle, core_specs)

    def write(self) -> None:
        """Rewrite the three files from the lifecycle's current view. Logs a failure, never raises."""
        if self.folder is None:
            return
        try:
            for name, content in self.contents().items():
                _write_atomic(self.folder / name, content)
        except Exception:
            log.exception("Couldn't write the generated files in %s", self.folder)

    def contents(self) -> dict[str, dict[str, Any]]:
        """Each file's name and JSON content."""
        lifecycle = self._lifecycle
        infos = lifecycle.modules()
        modules = [{"id": i.id, "state": str(i.state), "description": i.description} for i in infos]
        directory = []
        dependencies = {}
        for info in infos:
            menu = lifecycle.menu(info.id)
            directory.append({**info.model_dump(mode="json"),
                              "tools": [s.model_dump(mode="json") for s in (menu.specs() if menu else [])]})
            manifest = lifecycle.module_class(info.id).manifest
            dependencies[info.id] = {"needs": list(manifest.needs), "requires": list(info.requires),
                                     "packages": list(manifest.packages)}
        directory.append({"id": CORE_ID, "description": "The core's own menu: module control and grants",
                          "tools": [s.model_dump(mode="json") for s in self._core_specs()]})
        return {
            "modules.json": {"_generated": NOTE, "modules": modules},
            "directory.json": {"_generated": NOTE, "modules": directory},
            "dependencies.json": {"_generated": NOTE, "modules": dependencies},
        }


def _write_atomic(path: Path, content: dict[str, Any]) -> None:
    """Write beside the file, then replace it, so a reader never sees half a file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(content, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(temp, path)
